def window_stats(actual, pred, pct=0.10):
    """
    Returns % within ±pct window, % below, % above
    """
    lower = actual * (1 - pct)
    upper = actual * (1 + pct)
    within = (pred >= lower) & (pred <= upper)
    below  = pred < lower
    above  = pred > upper
    n = len(actual)
    return {
        'pct_within':  within.sum()  / n * 100,
        'pct_below':   below.sum()   / n * 100,
        'pct_above':   above.sum()   / n * 100,
    }

# Compute stats
train_stats = window_stats(y_true_train, y_pred_train, pct=0.10)
test_stats  = window_stats(y_true_test,  y_pred_test,  pct=0.10)

# Print
