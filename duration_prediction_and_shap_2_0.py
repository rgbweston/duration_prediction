    # Create TabularDataset for binary task (train only)
    ag_train = TabularDataset(X_train)
    label    = 'Overrun'

    # Initialize predictor (model saved at model_save_path)
    predictor = TabularPredictor(
        label        = label,
        problem_type = 'binary',
        eval_metric  = 'log_loss',
        path         = model_save_path,
        verbosity    = 3
    )
    print("Initialized new binary predictor at:", model_save_path)

    # Hyperparameters: all SHAP‐compatible tree models on CPU
