        lbl = f"{elapsed/60:.1f} min" if elapsed >= 60 else f"{elapsed:.0f} sec"
        print(f"\nLeaderboard (validation only) after {lbl}:")
        lb = predictor.leaderboard(ag_train, extra_info=False)
        print(lb[['model','score_val','eval_metric','fit_time']].head(10))

