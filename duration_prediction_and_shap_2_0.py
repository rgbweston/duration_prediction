    print(f"Running fit for up to {session_time/60:.1f} minutes "
          f"(remaining cap: {remaining_time/60:.1f} minutes).")

    # GPU check
    if torch.cuda.is_available():
        print(f"Number of GPUs available: {torch.cuda.device_count()}")
    else:
        print("No GPUs are available.")

    # Remove old model folder and recreate (train fresh)
    if os.path.exists(model_save_path):
        shutil.rmtree(model_save_path)
    os.makedirs(model_save_path, exist_ok=True)

    # Ensure 'Overrun' column exists
    for df_set in [train_data, test_data]:
        if 'Overrun' not in df_set.columns:
            df_set['Overrun'] = (df_set['Actual_Length'] > df_set['Expected_Length']).astype(int)

    # Show class balance
    ratio = train_data['Overrun'].mean()
    print(f"Overrun positive rate (train): {ratio:.2%}")

    # Drop leakage columns in feature set only
    features_to_drop = ['Expected_Length', 'Actual_Length']
    X_train = train_data.drop(columns=features_to_drop)
    y_train = train_data['Overrun']
